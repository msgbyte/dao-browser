namespace dao {

namespace {

constexpr char kIndexFileName[] = "WORKSPACE.md";

struct FileRow {
  std::string rel_path;
  int64_t bytes = 0;
  std::optional<int64_t> line_count;
};

std::optional<int64_t> CountNewlines(base::File file, int64_t size) {
  if (!file.IsValid()) {
    return std::nullopt;
  }
  std::array<uint8_t, 16384> buffer;
  int64_t count = 0;
  while (size > 0) {
    const size_t length =
        static_cast<size_t>(std::min<int64_t>(size, buffer.size()));
    auto chunk = base::span(buffer).first(length);
    const auto read = file.ReadAtCurrentPos(chunk);
    if (!read || *read == 0) {
      return std::nullopt;
    }
    count += std::ranges::count(chunk.first(*read), '\n');
    size -= static_cast<int64_t>(*read);
  }
  return count;
}

std::string FormatSize(int64_t bytes) {
  if (bytes < 1024) {
    return base::StringPrintf("%lld B", static_cast<long long>(bytes));
  }
  if (bytes < 1024 * 1024) {
    return base::StringPrintf("%.1f KB", bytes / 1024.0);
  }
  return base::StringPrintf("%.1f MB", bytes / (1024.0 * 1024.0));
}

}  // namespace

WorkspaceIndex::WorkspaceIndex(const base::FilePath& workspace_root)
    : workspace_root_(workspace_root) {}

WorkspaceIndex::~WorkspaceIndex() = default;

void WorkspaceIndex::Rewrite() {
  std::vector<FileRow> rows;
  int64_t total = 0;

  const auto status = ScanWorkspace(
      workspace_root_, {}, /*recursive=*/true, WorkspaceScanScope::kVisible,
      [&](const base::FilePath& path, const base::File::Info& info) {
        if (info.is_directory) {
          return;
        }
        FileRow row;
        row.rel_path = path.AsUTF8Unsafe();
        row.bytes = info.size;
        if (path.MatchesExtension(FILE_PATH_LITERAL(".md"))) {
          row.line_count =
              CountNewlines(OpenWorkspaceFile(workspace_root_, path), row.bytes);
        }
        total += row.bytes;
        rows.push_back(std::move(row));
      });
  if (status != WorkspaceError::kOk) {
    return;
  }

  std::sort(rows.begin(), rows.end(),
            [](const FileRow& a, const FileRow& b) {
              return a.rel_path < b.rel_path;
            });

  std::string out;
  out += "<!-- Auto-generated by Dao Agent. DO NOT EDIT — "
         "your changes will be overwritten. -->\n";
  out += "# Workspace Index\n\n";
  out += "Last updated: ";
  out += base::UTF16ToUTF8(
      base::TimeFormatShortDateAndTime(base::Time::Now()));
  out += "\n\n## Files\n";
  if (rows.empty()) {
    out += "(none)\n";
  } else {
    for (const auto& r : rows) {
      out += "- `";
      out += r.rel_path;
      out += "` (";
      out += FormatSize(r.bytes);
      if (r.line_count) {
        out += ", " + base::NumberToString(*r.line_count) + " lines";
      }
      out += ")\n";
    }
  }
  out += "\n## Stats\n";
  out += base::StringPrintf("- %zu files, %s total\n", rows.size(),
                            FormatSize(total).c_str());
  out += base::StringPrintf("- Quota: %s / 100 MB used\n",
                            FormatSize(total).c_str());

  WriteWorkspaceFile(workspace_root_, base::FilePath::FromASCII(kIndexFileName),
                     out);
}

}  // namespace dao
